# capstone index of calls + float constants of functions (exe + map)
"""Quick index (not a decompile): call targets and constant loads of selected TMNF functions -> re/model6_calls_consts.md.

Reference only: needs the helper modules map_symbols.py and port_tmuf.py from the author's unpublished physics project.
"""
import struct
import sys
from collections import Counter, OrderedDict
from pathlib import Path

from capstone import Cs, CS_ARCH_X86, CS_MODE_32, CS_OP_MEM, CS_OP_IMM, CS_GRP_CALL
from capstone.x86 import X86_OP_MEM

sys.path.insert(0, str(Path(__file__).resolve().parent))
import map_symbols as ms
from port_tmuf import Image, NF_EXE, func_sizes

OUT = Path(__file__).resolve().parent.parent / "re" / "model6_calls_consts.md"
TARGETS = ["ComputeForcesModel6", "GetLateralFriction", "ApplyFrictionForces",
           "ComputeVehicleGroundMaterialVals", "GetWheelFromSurfaceTree"]

md = Cs(CS_ARCH_X86, CS_MODE_32)
md.detail = True


def main():
    img = Image(NF_EXE)
    syms = ms.parse()
    by_va = {}
    for va, cls, meth, mangled, kind, obj in syms:
        by_va.setdefault(va, (cls + "::" + meth) if cls else meth)
    sizes = func_sizes()
    # section ranges to classify .rdata/.data
    secs = {s.Name.rstrip(b"\0").decode(): (img.base + s.VirtualAddress, img.base + s.VirtualAddress + s.Misc_VirtualSize)
            for s in img.pe.sections}

    def section_of(a):
        for n, (lo, hi) in secs.items():
            if lo <= a < hi:
                return n
        return None

    targets = [s for s in syms if s[1] == "CSceneVehicleCar" and s[2] in TARGETS and s[4] == "func"]
    lines = ["# Call and constant index (TMNF)", "",
             "Generated by `scripts/call_index.py` from `TmForever.exe` + `TmForever.map` with capstone. A quick index, not a decompile.",
             "Limits: immediate float constants (mov reg, 0x3f800000 / push imm) are not listed; linear disassembly can desync on trailing jump tables.",
             "Names come from the MSVC map (`Class::method`); `?` means no symbol. Constants are read as float (dword operand) or double (qword operand) from the exe image.",
             ""]
    for va, cls, meth, mangled, kind, obj in sorted(targets, key=lambda s: TARGETS.index(s[2])):
        size = sizes[va]
        code = img.read(va, size)
        calls = OrderedDict()
        indirect = Counter()
        consts = OrderedDict()
        globs = OrderedDict()
        for i in md.disasm(code, va):
            if i.id and i.group(CS_GRP_CALL) or i.mnemonic == "call":
                op = i.operands[0]
                if op.type == CS_OP_IMM:
                    calls.setdefault(op.imm, []).append(i.address)
                elif op.type == X86_OP_MEM and op.mem.base == 0 and op.mem.index == 0:
                    calls.setdefault(("ptr", op.mem.disp & 0xFFFFFFFF), []).append(i.address)
                else:
                    indirect[i.op_str] += 1
                continue
            for op in i.operands:
                if op.type == X86_OP_MEM and op.mem.base == 0 and op.mem.index == 0 and op.mem.segment == 0:
                    a = op.mem.disp & 0xFFFFFFFF
                    sec = section_of(a)
                    if sec is None:
                        continue
                    if sec.startswith(".rdata") and op.size in (4, 8) and (i.mnemonic.startswith("f") or "ss" in i.mnemonic or "sd" in i.mnemonic):
                        raw = img.read(a, op.size)
                        v = struct.unpack("<f" if op.size == 4 else "<d", raw)[0]
                        consts.setdefault((a, op.size), []).append((i.address, i.mnemonic))
                    elif not sec.startswith(".rdata") or op.size not in (4, 8):
                        globs.setdefault(a, []).append((i.address, i.mnemonic))
                    elif sec.startswith(".rdata"):
                        globs.setdefault(a, []).append((i.address, i.mnemonic))
        lines += ["## CSceneVehicleCar::%s  (%08x, %d bytes)" % (meth, va, size), "",
                  "### Direct calls (%d distinct targets)" % len(calls), "", "| call target | name | sites |", "|---|---|---|"]
        for t, sites in calls.items():
            if isinstance(t, tuple):
                tgt = t[1]
                name = "import/ptr [%08x] %s" % (tgt, by_va.get(tgt, "?"))
                lab = "[%08x]" % tgt
            else:
                lab = "%08x" % t
                name = by_va.get(t, "?")
            lines.append("| %s | `%s` | %s |" % (lab, name, ", ".join("%x" % s for s in sites[:6]) + (" ..." if len(sites) > 6 else "")))
        lines += ["", "### Indirect calls (virtual / register)", ""]
        if indirect:
            for k, n in indirect.most_common():
                lines.append("- `call %s` x%d" % (k, n))
        else:
            lines.append("- none")
        lines += ["", "### Float/double constants loaded from .rdata (%d)" % len(consts), "",
                  "| address | type | value | hex | used by (site: op) |", "|---|---|---|---|---|"]
        for (a, sz), uses in sorted(consts.items()):
            raw = img.read(a, sz)
            v = struct.unpack("<f" if sz == 4 else "<d", raw)[0]
            lines.append("| %08x | %s | %.9g | %s | %s |" % (a, "float" if sz == 4 else "double", v, raw[::-1].hex(),
                         ", ".join("%x: %s" % u for u in uses[:4]) + (" ..." if len(uses) > 4 else "")))
        lines += ["", "### Other absolute data addresses touched (%d)" % len(globs), "", "| address | section | symbol | sites |", "|---|---|---|---|"]
        for a, uses in sorted(globs.items()):
            lines.append("| %08x | %s | `%s` | %s |" % (a, section_of(a), by_va.get(a, "?"),
                         ", ".join("%x: %s" % u for u in uses[:3]) + (" ..." if len(uses) > 3 else "")))
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("written", OUT)


if __name__ == "__main__":
    main()
